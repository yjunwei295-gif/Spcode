const packs = { zh, en };

function normalize(loc) {
  return loc === 'en' ? 'en' : 'zh';
}

export function getLocale() {
  return locale;
}

export function setLocale(loc) {
  locale = normalize(loc);
  return locale;
}

export function t(key, vars) {
  let s = (packs[locale] && packs[locale][key]) || zh[key] || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

export function applyDom() {
  document.documentElement.lang = locale === 'en' ? 'en' : 'zh-CN';
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  });
  document.querySelectorAll('#lang-switch [data-locale]').forEach((btn) => {
    btn.classList.toggle('on', btn.getAttribute('data-locale') === locale);
  });
}

export function isNewChatTitle(title) {
  return title === zh.newChat || title === en.newChat;
}

